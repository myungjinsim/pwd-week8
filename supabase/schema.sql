    alter table public.restaurants add constraint foodmap_restaurant_values check (
      length(btrim(name)) between 1 and 300 and length(btrim(category)) between 1 and 300
      and length(btrim(location)) between 1 and 300 and rating between 0 and 5 and likes >= 0
